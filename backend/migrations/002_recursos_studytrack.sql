-- Consumir o token e trocar a senha em uma transação evita reutilização concorrente.
create or replace function public.consumir_token_redefinicao(p_token_hash text, p_novo_hash text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_usuario_id integer;
begin
  update public.tokens_redefinicao_senha
     set usado_em = now()
   where token_hash = p_token_hash
     and usado_em is null
     and expira_em > now()
  returning usuario_id into v_usuario_id;

  if v_usuario_id is null then
    return false;
  end if;

  update public.usuarios
     set senha_hash = p_novo_hash, atualizado_em = now()
   where id = v_usuario_id;

  return found;
end;
$$;

-- Reserva atômica. Se uma tentativa não enviou a nenhum dispositivo, permite nova
-- tentativa após 10 minutos, sem liberar duplicação de notificações já enviadas.
create or replace function public.reservar_notificacao(
    p_usuario_id integer, p_tipo text, p_referencia_id integer, p_janela text)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_id bigint;
begin
  insert into public.notificacoes_processadas
    (usuario_id, tipo, referencia_id, janela, status)
  values (p_usuario_id, p_tipo, p_referencia_id, p_janela, 'processando')
  on conflict (usuario_id, tipo, referencia_id, janela)
  do update set status = 'processando', atualizado_em = now()
    where public.notificacoes_processadas.status = 'falha'
      and public.notificacoes_processadas.atualizado_em < now() - interval '10 minutes'
  returning id into v_id;
  return v_id;
end;
$$;

revoke all on function public.consumir_token_redefinicao(text, text) from public, anon, authenticated;
revoke all on function public.reservar_notificacao(integer, text, integer, text) from public, anon, authenticated;
grant execute on function public.consumir_token_redefinicao(text, text) to service_role;
grant execute on function public.reservar_notificacao(integer, text, integer, text) to service_role;

-- A exclusão da conta é feita em uma única transação PostgreSQL.
-- O Flask confirma a senha atual e só permite o próprio usuario_id do JWT.
create or replace function public.excluir_conta_studytrack(p_usuario_id integer)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not exists (select 1 from public.usuarios where id = p_usuario_id) then
    return false;
  end if;

  delete from public.horarios_aula where materia_id in
    (select id from public.materias where usuario_id = p_usuario_id);
  delete from public.tarefas where materia_id in
    (select id from public.materias where usuario_id = p_usuario_id);
  delete from public.exames where materia_id in
    (select id from public.materias where usuario_id = p_usuario_id);
  -- Códigos QR e suas leituras acompanham a exclusão das matérias por CASCADE.
  delete from public.materias where usuario_id = p_usuario_id;
  delete from public.dispositivos where usuario_id = p_usuario_id;
  delete from public.locais where usuario_id = p_usuario_id;
  delete from public.preferencias_notificacao where usuario_id = p_usuario_id;
  delete from public.tokens_revogados where usuario_id = p_usuario_id;
  -- Tokens de redefinição e histórico de notificações usam ON DELETE CASCADE.
  delete from public.usuarios where id = p_usuario_id;
  return found;
end;
$$;

revoke all on function public.excluir_conta_studytrack(integer) from public, anon, authenticated;
grant execute on function public.excluir_conta_studytrack(integer) to service_role;

create table if not exists public.tokens_redefinicao_senha (
  token_hash text primary key,
  usuario_id integer not null references public.usuarios(id) on delete cascade,
  expira_em timestamptz not null,
  usado_em timestamptz,
  criado_em timestamptz not null default now()
);
create index if not exists idx_redefinicao_usuario_criado
  on public.tokens_redefinicao_senha (usuario_id, criado_em desc);
create index if not exists idx_redefinicao_expira
  on public.tokens_redefinicao_senha (expira_em);

-- Código QR aponta para uma matéria do próprio estudante.
create table if not exists public.codigos_qr (
  id bigint generated by default as identity primary key,
  materia_id integer not null references public.materias(id) on delete cascade,
  codigo text not null unique,
  tipo text not null check (tipo in ('material', 'tarefa', 'exame')),
  titulo text not null,
  url text,
  referencia_id integer,
  criado_em timestamptz not null default now(),
  check (
    (tipo = 'material' and url is not null and referencia_id is null)
    or (tipo in ('tarefa', 'exame') and referencia_id is not null and url is null)
  )
);
create index if not exists idx_codigos_qr_materia on public.codigos_qr (materia_id);

create table if not exists public.leituras_qr (
  id bigint generated by default as identity primary key,
  codigo_qr_id bigint not null references public.codigos_qr(id) on delete cascade,
  usuario_id integer not null references public.usuarios(id) on delete cascade,
  lido_em timestamptz not null default now()
);
create index if not exists idx_leituras_qr_usuario on public.leituras_qr (usuario_id, lido_em desc);

-- Evita disparar o mesmo lembrete duas vezes quando duas execuções se sobrepõem.
create table if not exists public.notificacoes_processadas (
  id bigint generated by default as identity primary key,
  usuario_id integer not null references public.usuarios(id) on delete cascade,
  tipo text not null check (tipo in ('tarefa', 'exame', 'estudo')),
  referencia_id integer not null,
  janela text not null,
  status text not null default 'processando' check (status in ('processando','enviado','falha')),
  enviado_em timestamptz,
  atualizado_em timestamptz not null default now(),
  unique (usuario_id, tipo, referencia_id, janela)
);
create index if not exists idx_notificacoes_processadas_usuario
  on public.notificacoes_processadas (usuario_id, atualizado_em desc);

-- Só o backend com chave service_role deve acessar estas tabelas diretamente.
alter table public.tokens_redefinicao_senha enable row level security;
